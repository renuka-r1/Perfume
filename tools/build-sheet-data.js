#!/usr/bin/env node
/*
 * Builds js/sheet-data.js from the spreadsheet export and the hand-written
 * scent/gender annotations:
 *
 *   node tools/build-sheet-data.js
 *
 * Inputs:  data/middle-eastern-clones-2024.csv  (the Google Sheet, saved as CSV)
 *          data/annotations.txt                  (row → gender + accords)
 */
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
global.window = {};
require(path.join(root, "js/data.js"));
require(path.join(root, "js/engine.js"));
const E = window.ScentEngine;

const CODES = {
  ci: "citrus", aq: "aquatic", gr: "green", ar: "aromatic", la: "lavender", fr: "fruity", tr: "tropical",
  fl: "floral", ro: "rose", wf: "whitefloral", po: "powdery", mu: "musky", va: "vanilla", go: "gourmand",
  co: "coffee", bo: "boozy", am: "amber", wo: "woody", ou: "oud", sp: "spicy", le: "leather", to: "tobacco",
  sm: "smoky", ea: "earthy",
};
const GENDER = { m: "men", f: "women", u: "unisex" };

const notes = {};
for (const line of fs.readFileSync(path.join(root, "data/annotations.txt"), "utf8").split("\n")) {
  const t = line.trim();
  if (!t || t.startsWith("#")) continue;
  const [row, g, ...acc] = t.split(/\s+/);
  for (const a of acc) if (!CODES[a]) throw new Error(`Row ${row}: unknown accord code "${a}"`);
  notes[row] = { gender: GENDER[g], accords: acc.map((a) => CODES[a]) };
}

const rows = E.parseDelimited(fs.readFileSync(path.join(root, "data/middle-eastern-clones-2024.csv"), "utf8"));
const { headers, body } = E.splitTable(rows);
const mapping = E.guessMapping(headers, body);
// Sheet row number for each body row (header is row 1).
const rowNums = [];
rows.forEach((r, i) => { if (i > 0 && r.some((c) => String(c).trim())) rowNums.push(i + 1); });

const style = E.dupeStyle(body.map((r) => r[mapping.dupe] || ""));
const out = [];
let missing = 0;
body.forEach((r, i) => {
  const [rec] = E.recordsFromTable([r], mapping, style);
  if (!rec) return;
  const a = notes[rowNums[i]];
  if (!a) missing++;
  out.push({ house: rec.house, name: rec.name, gender: a ? a.gender : rec.gender || null, accords: a ? a.accords : [], dupes: rec.dupes });
});

const header = "/* Generated by tools/build-sheet-data.js from data/middle-eastern-clones-2024.csv. Do not edit by hand. */\n";
fs.writeFileSync(path.join(root, "js/sheet-data.js"), header + "window.SHEET_PERFUMES = " + JSON.stringify(out) + ";\n");
console.log(`${out.length} originals, ${out.reduce((s, r) => s + r.dupes.length, 0)} dupes, ${missing} without annotations`);
